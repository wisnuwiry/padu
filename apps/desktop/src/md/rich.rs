//! Rich markdown rendering: LaTeX → SVG (MathJax) and Mermaid → SVG, produced
//! by a dedicated QuickJS worker isolate, cached on disk and in memory, and
//! handed to GPUI as SVG [`Image`]s that its own asset system rasterizes and
//! repaints asynchronously.
//!
//! Ownership of the isolate stays on a single background thread, so the GPUI
//! render thread never runs JS: a render pass only locks the in-memory cache
//! (a hash lookup) and enqueues a request when the block is unknown. The worker
//! resolves requests serially, checks the disk cache first, renders through
//! the JS bundle when it must, persists the SVG, and marks the entry ready —
//! which the image source loader observes on its next poll and repaints.
//!
//! The JS bundles live in `rich/js/` and are regenerated by
//! `scripts/build-rich-render.ts`; they are committed so the crate compiles
//! offline. KaTeX is the web client's math engine but only emits HTML/CSS,
//! never SVG, so the desktop isolate uses MathJax v3's SVG output jax with the
//! same `$…$`/`$$…$$` surface and macro set.

use std::collections::{HashMap, VecDeque};
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, OnceLock};
use std::time::{Duration, Instant, SystemTime};

use crossbeam_channel::{Receiver, Sender};
use gpui::{App, Image, ImageCacheError, ImageFormat, ImageSource, RenderImage, Window};
use parking_lot::Mutex;
use rquickjs::{Context, Function, Promise, Runtime, Value};
use serde::Serialize;

const MATH_BUNDLE: &str = include_str!("rich/js/math.bundle.js");
const MERMAID_BUNDLE: &str = include_str!("rich/js/mermaid.bundle.js");

const CACHE_DIR_NAME: &str = "render-cache";
/// Disk cache cap for `~/.padu/render-cache/`. Eviction removes the oldest
/// files by modified time until the directory sits under the cap again.
const DISK_CAP_BYTES: u64 = 64 * 1024 * 1024;
/// In-memory entry cap, approximate LRU by insertion order.
const MEMORY_CAP_ENTRIES: usize = 256;
/// Upper bound for a single JS render before the worker reports a timeout.
const RENDER_DEADLINE: Duration = Duration::from_secs(30);
/// Cadence at which a pending image source re-checks the cache.
const WAIT_POLL: Duration = Duration::from_millis(50);

/// What kind of rich content a render request carries.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RichKind {
    Math { display: bool },
    Mermaid,
}

impl RichKind {
    fn tag(self) -> &'static str {
        match self {
            RichKind::Math { display: true } => "math-display",
            RichKind::Math { display: false } => "math-inline",
            RichKind::Mermaid => "mermaid",
        }
    }
}

/// Theme colors for a rich render, serialized straight to the JS call. Every
/// value participates in the cache key so a theme switch re-renders rather
/// than reusing an SVG painted for the other appearance.
#[derive(Clone, Debug, Serialize)]
pub struct RenderTheme {
    pub is_dark: bool,
    pub font_px: f32,
    pub text: String,
    pub secondary: String,
    pub tertiary: String,
    pub border: String,
    pub card: String,
    pub surface: String,
    pub accent: String,
    pub success: String,
    pub warning: String,
    pub danger: String,
    pub font_family: String,
}

impl RenderTheme {
    pub fn signature(&self) -> String {
        let font_px = self.font_px.to_string();
        [
            if self.is_dark { "d" } else { "l" },
            font_px.as_str(),
            self.text.as_str(),
            self.secondary.as_str(),
            self.tertiary.as_str(),
            self.border.as_str(),
            self.card.as_str(),
            self.surface.as_str(),
            self.accent.as_str(),
            self.success.as_str(),
            self.warning.as_str(),
            self.danger.as_str(),
            self.font_family.as_str(),
        ]
        .join("|")
    }

    pub fn to_json(&self) -> String {
        serde_json::to_string(self).unwrap_or_else(|_| "{}".into())
    }
}

/// Content-addressed key for a rich block: kind + source + theme colors.
pub fn hash(kind: RichKind, source: &str, theme: &RenderTheme) -> u64 {
    let mut hasher = blake3::Hasher::new();
    hasher.update(kind.tag().as_bytes());
    hasher.update(&[0]);
    hasher.update(source.as_bytes());
    hasher.update(&[0]);
    hasher.update(theme.signature().as_bytes());
    let out = hasher.finalize();
    u64::from_le_bytes(
        out.as_bytes()[..8]
            .try_into()
            .expect("blake3 output is 32 bytes"),
    )
}

// ── Cache ──────────────────────────────────────────────────────────────────

enum Entry {
    Ready { image: Arc<Image> },
    Error { message: String },
    InFlight,
}

struct CacheInner {
    entries: HashMap<u64, Entry>,
    order: VecDeque<u64>,
}

struct DiskCache {
    dir: PathBuf,
}

impl DiskCache {
    fn new() -> Self {
        let dir = crate::projectless::home_directory()
            .or_else(|| dirs::home_dir().map(|home| home.join(".padu")))
            .map(|home| home.join(CACHE_DIR_NAME))
            .unwrap_or_else(|| std::env::temp_dir().join("padu-render-cache"));
        Self { dir }
    }

    fn path(&self, hash: u64) -> PathBuf {
        self.dir.join(format!("{hash:016x}.svg"))
    }

    fn load(&self, hash: u64) -> Option<String> {
        std::fs::read_to_string(self.path(hash)).ok()
    }

    fn save(&self, hash: u64, svg: &str) {
        if std::fs::create_dir_all(&self.dir).is_err() {
            return;
        }
        let _ = std::fs::write(self.path(hash), svg);
        self.enforce_cap();
    }

    /// Evict the oldest files until the directory total is under the cap.
    fn enforce_cap(&self) {
        let mut files: Vec<(SystemTime, PathBuf)> = match std::fs::read_dir(&self.dir) {
            Ok(entries) => entries
                .filter_map(|entry| {
                    let entry = entry.ok()?;
                    if entry.file_type().ok()?.is_file() {
                        let modified = entry.metadata().ok()?.modified().ok()?;
                        Some((modified, entry.path()))
                    } else {
                        None
                    }
                })
                .collect(),
            Err(_) => return,
        };
        let total: u64 = files
            .iter()
            .map(|(_, path)| path.metadata().map(|meta| meta.len()).unwrap_or(0))
            .sum();
        if total <= DISK_CAP_BYTES {
            return;
        }
        files.sort();
        let mut removed = 0u64;
        for (_, path) in files {
            if total - removed <= DISK_CAP_BYTES {
                break;
            }
            if let Ok(size) = path.metadata().map(|meta| meta.len()) {
                if std::fs::remove_file(&path).is_ok() {
                    removed += size;
                }
            }
        }
    }
}

pub struct RichCache {
    inner: Mutex<CacheInner>,
    disk: DiskCache,
}

impl RichCache {
    fn new() -> Self {
        Self {
            inner: Mutex::new(CacheInner {
                entries: HashMap::new(),
                order: VecDeque::new(),
            }),
            disk: DiskCache::new(),
        }
    }

    /// True once the entry has settled into a ready image or an error; an
    /// in-flight marker is not enough for a waiter to stop polling.
    fn settled(&self, hash: u64) -> bool {
        matches!(
            self.inner.lock().entries.get(&hash),
            Some(Entry::Ready { .. } | Entry::Error { .. })
        )
    }
}

/// What the image source loader should paint while the cache resolves.
#[derive(Debug)]
pub enum RenderOutcome {
    Ready(Arc<Image>),
    Error(String),
    Pending,
}

/// A request queued to the worker thread.
pub struct WorkerRequest {
    pub hash: u64,
    pub kind: RichKind,
    pub source: String,
    pub theme: RenderTheme,
}

pub struct RichRenderer {
    cache: Arc<RichCache>,
    worker: Sender<WorkerRequest>,
}

static RICH: OnceLock<Arc<RichRenderer>> = OnceLock::new();

impl RichRenderer {
    fn spawn() -> Arc<Self> {
        let cache = Arc::new(RichCache::new());
        let (sender, receiver) = crossbeam_channel::unbounded::<WorkerRequest>();
        let worker_cache = cache.clone();
        std::thread::Builder::new()
            .name("padu-rich-render".into())
            .spawn(move || worker_loop(receiver, worker_cache))
            .expect("could not spawn the rich-render worker");
        Arc::new(Self {
            cache,
            worker: sender,
        })
    }

    fn ensure(
        &self,
        hash: u64,
        kind: RichKind,
        source: String,
        theme: RenderTheme,
    ) -> RenderOutcome {
        {
            let mut inner = self.cache.inner.lock();
            match inner.entries.get(&hash) {
                Some(Entry::Ready { image }) => return RenderOutcome::Ready(image.clone()),
                Some(Entry::Error { message }) => return RenderOutcome::Error(message.clone()),
                Some(Entry::InFlight) => return RenderOutcome::Pending,
                None => {}
            }
            inner.entries.insert(hash, Entry::InFlight);
            inner.order.push_back(hash);
            while inner.entries.len() > MEMORY_CAP_ENTRIES {
                let Some(old) = inner.order.pop_front() else {
                    break;
                };
                if old != hash {
                    inner.entries.remove(&old);
                }
            }
        }
        let _ = self.worker.send(WorkerRequest {
            hash,
            kind,
            source,
            theme,
        });
        RenderOutcome::Pending
    }

    fn settled(&self, hash: u64) -> bool {
        self.cache.settled(hash)
    }
}

impl RichCache {
    fn complete(&self, hash: u64, result: Result<String, String>) {
        {
            let mut inner = self.inner.lock();
            let Some(previous) = inner.entries.remove(&hash) else {
                return;
            };
            if !matches!(previous, Entry::InFlight) {
                return;
            }
            let entry = match result {
                Ok(svg) => Entry::Ready {
                    image: Arc::new(Image::from_bytes(ImageFormat::Svg, svg.into_bytes())),
                },
                Err(message) => Entry::Error { message },
            };
            inner.entries.insert(hash, entry);
            inner.order.push_back(hash);
        }
        // The loader's poll loop observes the ready entry and repaints; no
        // cross-thread wake is needed.
    }
}

/// Build the `ImageSource` for a rich block. The loader resolves from the
/// cache each layout pass: ready SVG is rasterized by GPUI's asset system,
/// errors surface through `with_fallback`, and a pending block enqueues the
/// render (once) and schedules a repaint when it lands.
pub fn rich_image_source(
    hash: u64,
    kind: RichKind,
    source: String,
    theme: RenderTheme,
) -> impl Fn(&mut Window, &mut App) -> Option<Result<Arc<RenderImage>, ImageCacheError>> + 'static {
    let cache: Arc<RichRenderer> = RICH.get_or_init(RichRenderer::spawn).clone();
    move |window, cx| match cache.ensure(hash, kind, source.clone(), theme.clone()) {
        RenderOutcome::Ready(image) => image.use_render_image(window, cx).map(Ok),
        RenderOutcome::Error(message) => Some(Err(ImageCacheError::Other(Arc::new(
            anyhow::anyhow!(message),
        )))),
        RenderOutcome::Pending => {
            let wait_cache = cache.clone();
            window
                .spawn(cx, async move |cx| {
                    let deadline = Instant::now() + RENDER_DEADLINE;
                    while Instant::now() < deadline {
                        if wait_cache.settled(hash) {
                            break;
                        }
                        cx.background_executor().timer(WAIT_POLL).await;
                    }
                    cx.refresh();
                })
                .detach();
            None
        }
    }
}

/// The `ImageSource` value for a rich block, ready for `img(...)`.
pub fn rich_image_source_value(
    hash: u64,
    kind: RichKind,
    source: String,
    theme: RenderTheme,
) -> ImageSource {
    ImageSource::Custom(Arc::new(rich_image_source(hash, kind, source, theme)))
}

// ── Worker ─────────────────────────────────────────────────────────────────

fn worker_loop(receiver: Receiver<WorkerRequest>, cache: Arc<RichCache>) {
    let mut isolate: Option<Result<RichIsolate, String>> = None;
    while let Ok(request) = receiver.recv() {
        let result = match cache.disk.load(request.hash) {
            Some(svg) => Ok(svg),
            None => {
                let rendered = match &mut isolate {
                    Some(Err(message)) => Err(message.clone()),
                    Some(Ok(iso)) => iso.render(&request),
                    None => {
                        let built = RichIsolate::new().map_err(|error| error.to_string());
                        let rendered = match &built {
                            Ok(iso) => iso.render(&request),
                            Err(message) => Err(message.clone()),
                        };
                        isolate = Some(built);
                        rendered
                    }
                };
                if let Ok(svg) = &rendered {
                    cache.disk.save(request.hash, svg);
                }
                rendered
            }
        };
        cache.complete(request.hash, result);
    }
}

/// The QuickJS isolate. Owned exclusively by the worker thread, so it is not
/// `Send`; the renderer never touches it from the GPUI thread.
struct RichIsolate {
    context: Context,
    _runtime: Runtime,
}

impl RichIsolate {
    fn new() -> anyhow::Result<Self> {
        use anyhow::Context as _;
        let runtime = Runtime::new().context("could not create the QuickJS runtime")?;
        runtime.set_memory_limit(512 * 1024 * 1024);
        runtime.set_max_stack_size(8 * 1024 * 1024);
        let context = Context::full(&runtime).context("could not create the QuickJS context")?;
        context
            .with(|ctx| -> Result<(), String> {
                // QuickJS has no `console` or timers; libraries use both defensively.
                // `setTimeout` defers work some diagram paths rely on, so the
                // stub runs the callback immediately rather than dropping it.
                ctx.eval::<(), _>(
                    "globalThis.console = { log(){}, warn(){}, error(){}, info(){}, debug(){}, trace(){} };\
                     globalThis.setTimeout = function (fn) { if (typeof fn === 'function') { fn(); } return 0; };\
                     globalThis.clearTimeout = function () {};\
                     globalThis.setInterval = function () { return 0; };\
                     globalThis.clearInterval = function () {};",
                )
                .map_err(|error| quickjs_message(&ctx, &error))?;
                ctx.eval::<(), _>(MATH_BUNDLE)
                    .map_err(|error| quickjs_message(&ctx, &error))?;
                ctx.eval::<(), _>(MERMAID_BUNDLE)
                    .map_err(|error| quickjs_message(&ctx, &error))?;
                Ok(())
            })
            .map_err(|message| anyhow::anyhow!("{message}"))
            .context("could not initialize the rich-render isolate")?;
        Ok(Self {
            context,
            _runtime: runtime,
        })
    }

    fn render(&self, request: &WorkerRequest) -> Result<String, String> {
        match request.kind {
            RichKind::Math { display } => {
                self.render_math(&request.source, display, &request.theme)
            }
            RichKind::Mermaid => self.render_mermaid(&request.source, &request.theme),
        }
    }

    fn render_math(
        &self,
        source: &str,
        display: bool,
        theme: &RenderTheme,
    ) -> Result<String, String> {
        self.context.with(|ctx| {
            let globals = ctx.globals();
            let render: Function<'_> = globals
                .get("__paduRenderMath")
                .map_err(|error| quickjs_message(&ctx, &error))?;
            let theme_json = theme.to_json();
            let result: Value<'_> = render
                .call((source, display, theme_json))
                .map_err(|error| quickjs_message(&ctx, &error))?;
            let object = result
                .into_object()
                .ok_or_else(|| "math render returned a non-object".to_string())?;
            if let Ok(svg) = object.get::<_, String>("svg") {
                Ok(svg)
            } else {
                let message: String = object
                    .get("error")
                    .unwrap_or_else(|_| "math render failed".into());
                Err(message)
            }
        })
    }

    fn render_mermaid(&self, source: &str, theme: &RenderTheme) -> Result<String, String> {
        self.context.with(|ctx| {
            let globals = ctx.globals();
            let render: Function<'_> = globals
                .get("__paduRenderMermaid")
                .map_err(|error| quickjs_message(&ctx, &error))?;
            let id = format!("padu-m-{}", next_mermaid_id());
            let theme_json = theme.to_json();
            let promise: Promise<'_> = render
                .call((id, source, theme_json))
                .map_err(|error| quickjs_message(&ctx, &error))?;
            let deadline = Instant::now() + RENDER_DEADLINE;
            loop {
                while ctx.execute_pending_job() {}
                if let Some(result) = promise.result::<Value<'_>>() {
                    let value = result.map_err(|error| quickjs_message(&ctx, &error))?;
                    let object = value
                        .into_object()
                        .ok_or_else(|| "diagram render returned a non-object".to_string())?;
                    return object
                        .get::<_, String>("svg")
                        .map_err(|error| quickjs_message(&ctx, &error));
                }
                if Instant::now() >= deadline {
                    return Err("diagram rendering timed out".into());
                }
                std::thread::sleep(Duration::from_millis(2));
            }
        })
    }
}

fn next_mermaid_id() -> u64 {
    static NEXT: AtomicU64 = AtomicU64::new(1);
    NEXT.fetch_add(1, Ordering::Relaxed)
}

fn quickjs_message(ctx: &rquickjs::Ctx<'_>, error: &rquickjs::Error) -> String {
    if matches!(error, rquickjs::Error::Exception) {
        let caught = ctx.catch();
        if let Ok(exception) = rquickjs::Exception::from_value(caught.clone()) {
            return exception
                .message()
                .or_else(|| exception.stack())
                .unwrap_or_else(|| "JavaScript execution failed".into());
        }
        if let Some(string) = caught
            .as_string()
            .and_then(|string| string.to_string().ok())
        {
            return string;
        }
    }
    error.to_string()
}

